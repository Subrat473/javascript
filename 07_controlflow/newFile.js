const { month } = require("./switch");

switch (month) {
    case jan:
        console.log("January");
        break;
    case feb:
        console.log("feby");
        break;
    case march:
        console.log("march");
        break;
    case april:
        console.log("april");
        break;
    case may:
        console.log("may");
        break;

    default:
        console.log("default case match");

        break;
}
